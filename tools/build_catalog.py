"""Write js/catalog.js from curriculum tables, and the language reference pages."""
import html
from pathlib import Path

root = Path(__file__).resolve().parents[1]
curriculum = root / "curriculum"


def table_rows(path, header_prefix):
    lines = path.read_text(encoding="utf-8").splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith(header_prefix))
    header = lines[start].split("\t")
    rows = []
    for line in lines[start + 1 :]:
        if not line.strip():
            continue
        if line.startswith("#"):
            break
        cells = line.split("\t")
        if len(cells) < len(header):
            cells += [""] * (len(header) - len(cells))
        rows.append(dict(zip(header, cells[: len(header)])))
    return rows


def js_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def split_list(value):
    if not value or not value.strip():
        return []
    return [part.strip() for part in value.split(";") if part.strip()]


def write_glossary():
    rows = table_rows(curriculum / "glossary.tsv", "id\tgroup\t")
    lines = [
        "/* Generated by tools/build_catalog.py. Do not edit by hand. */",
        "window.GLOSSARY = {",
        "  entries: [",
    ]
    for row in rows:
        aliases = ", ".join(js_string(part) for part in split_list(row.get("aliases", "")))
        also = ", ".join(js_string(part) for part in split_list(row.get("also", "")))
        stub = "true" if row.get("stub", "").strip().lower() == "yes" else "false"
        lines.append(
            "    { id: %s, group: %s, term: %s, aliases: [%s], brief: %s, body: %s, stub: %s, see: %s, also: [%s], page: %s, advanced: %s },"
            % (
                js_string(row["id"]),
                js_string(row["group"]),
                js_string(row["term"]),
                aliases,
                js_string(row.get("brief", "")),
                js_string(row.get("body", "")),
                stub,
                js_string(row.get("see", "")),
                also,
                js_string(row.get("page", "")),
                js_string(row.get("advanced", "")),
            )
        )
    lines.append("  ]")
    lines.append("};")
    lines.append("")
    (root / "js" / "glossary.js").write_text("\n".join(lines), encoding="utf-8")
    print("%s glossary" % len(rows))


def term_link(term_id, label):
    return (
        '<a class="term" data-term="%s" href="/#/glossary/%s" target="_blank" rel="noopener">%s</a>'
        % (html.escape(term_id), html.escape(term_id), html.escape(label))
    )


def ext_link(url, label):
    return '<a href="%s" target="_blank" rel="noopener">%s</a>' % (
        html.escape(url, quote=True),
        html.escape(label),
    )


